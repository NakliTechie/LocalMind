// Packs llama.cpp's i-quant codebooks (ggml-common.h) into the compact base64 strings src/iq_quants.js decodes.
// Every grid byte comes from a small value set, so each entry packs into a few bits:
//   iq2xxs / iq2xs / iq2s (uint64, bytes ∈ {0x08, 0x19, 0x2b})  → 2 bits × 8 = u16 per entry
//   iq3xxs (uint32, bytes ∈ {4, 12, …, 62}), iq3s (bytes ∈ {1, 3, …, 15}) → 3 bits × 4 = u16 per entry
//   iq1s                  (uint64 of int8 ∈ {-1, 0, 1})          → 2 bits × 8 = u16 per entry
// The script refuses any byte outside its set, so a changed codebook cannot pack silently wrong.
//
//   node scripts/build-iq-grids.mjs [path/to/ggml-common.h]   # prints the GRIDS object literal
import { readFileSync } from 'node:fs';
import { homedir } from 'node:os';

const path = process.argv[2] || `${homedir()}/Code/llama.cpp-dev/ggml/src/ggml-common.h`;
const src = readFileSync(path, 'utf8');
const table = (name) => {
  const m = new RegExp(`GGML_TABLE_BEGIN\\(\\w+, ${name}, \\w+\\)([\\s\\S]*?)GGML_TABLE_END`).exec(src);
  if (!m) throw new Error(`table ${name} not found in ${path}`);
  return [...m[1].matchAll(/-?0x[0-9a-fA-F]+|-?\d+/g)].map((t) => BigInt(t[0]));
};
const SETS = {
  iq2: [0x08, 0x19, 0x2b],
  iq3xxs: [0x04, 0x0c, 0x14, 0x1c, 0x24, 0x2c, 0x34, 0x3e],
  iq3s: [0x01, 0x03, 0x05, 0x07, 0x09, 0x0b, 0x0d, 0x0f],
  iq1: [0xff, 0x00, 0x01],   // int8 -1, 0, 1 as bytes
};
const pack = (name, bytesPerEntry, set, bits, expectLen) => {
  const vals = table(name);
  if (vals.length !== expectLen) throw new Error(`${name}: ${vals.length} entries, expected ${expectLen}`);
  const out = new Uint16Array(vals.length);
  vals.forEach((v, e) => {
    let code = 0;
    for (let j = 0; j < bytesPerEntry; j++) {
      const byte = Number((v >> BigInt(8 * j)) & 0xffn);
      const k = set.indexOf(byte);
      if (k < 0) throw new Error(`${name}[${e}] byte ${j} = 0x${byte.toString(16)} is outside its value set`);
      code |= k << (bits * j);
    }
    out[e] = code;
  });
  return Buffer.from(out.buffer).toString('base64');
};
const kvalues = table('kvalues_iq4nl').map(Number);
if (kvalues.length !== 16) throw new Error('kvalues_iq4nl must have 16 entries');
const grids = {
  iq2xxs: pack('iq2xxs_grid', 8, SETS.iq2, 2, 256),
  iq2xs: pack('iq2xs_grid', 8, SETS.iq2, 2, 512),
  iq2s: pack('iq2s_grid', 8, SETS.iq2, 2, 1024),
  iq3xxs: pack('iq3xxs_grid', 4, SETS.iq3xxs, 3, 256),
  iq3s: pack('iq3s_grid', 4, SETS.iq3s, 3, 512),
  iq1s: pack('iq1s_grid', 8, SETS.iq1, 2, 2048),
};
console.log(`// Generated by scripts/build-iq-grids.mjs from llama.cpp ggml-common.h. Do not edit by hand.`);
console.log(`const KVALUES_IQ4NL = [${kvalues.join(', ')}];`);
console.log(`const GRIDS = {`);
for (const [k, v] of Object.entries(grids)) console.log(`  ${k}: '${v}',`);
console.log(`};`);
